function iseven(num)
{
    return num%2==0;
}
console.log(iseven(1));
console.log(iseven(2));

function maxnum(num1,num2)
{
    return  num1>num2 ? num1:num2;
}
console.log(maxnum(10,25));
console.log(maxnum(99,3));
